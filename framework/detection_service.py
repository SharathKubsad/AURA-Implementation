    def predict_proba(
        self,
        proc: ProcessFeatures,
        cmd: CommandFeatures,
        net: NetworkFeatures,
        mem: MemoryFeatures | None = None,
        force_memory_trigger: bool = False,
    ) -> float:
        """Predict fused malware probability for given telemetry schemas."""
        res = self.detect(
            proc=proc,
            cmd=cmd,
            net=net,
            mem=mem,
            force_memory_trigger=force_memory_trigger,
        )
        return float(res["confidence"])

    def predict(
        self,
        proc: ProcessFeatures,
        cmd: CommandFeatures,
        net: NetworkFeatures,
        mem: MemoryFeatures | None = None,
        threshold: float | None = None,
        force_memory_trigger: bool = False,
    ) -> int:
        """Predict binary class (0: Benign, 1: Malware) for given telemetry schemas."""
        conf = self.predict_proba(
            proc=proc,
            cmd=cmd,
            net=net,
            mem=mem,
            force_memory_trigger=force_memory_trigger,
        )
        th = threshold if threshold is not None else self.fusion_engine.threshold
        return int(conf >= th)
