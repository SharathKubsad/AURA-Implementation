class DetectionService:
    """Singleton-style detection engine hosting all models and collectors."""

    def __init__(self, root_dir: Path | str = ".") -> None:
        self.root_dir = Path(root_dir)
        self.fusion_engine = HybridFusionEngine(self.root_dir / "configs" / "thresholds.yaml")

        # Collectors
        self.proc_collector = ProcessCollector() if ProcessCollector is not None else None
        self.cmd_collector = CommandCollector() if CommandCollector is not None else None
        self.net_collector = NetworkCollector() if NetworkCollector is not None else None
        self.mem_trigger = MemoryTrigger() if MemoryTrigger is not None else None

        # Models
        self.process_model: ProcessModel | None = None
        self.memory_model: MemoryModel | None = None
        self.command_model: CommandModel | None = None
        self.network_model: NetworkModel | None = None
        self.multiclass_model: XGBClassifier | None = None

        # Multiclass label mapping (encoded index -> family name)
        # Loaded from label_mapping.json generated by train_on_custom.py
        self.multiclass_label_map: dict[int, str] = dict(FAMILY_LABEL_MAP)  # fallback default

        self.load_models()

    def load_models(self) -> None:
        """Load serialized model artifacts into memory."""
        # 1. Process Model (XGBoost)
        proc_p = self.root_dir / "models" / "artifacts" / "process"
        if proc_p.exists():
            try:
                self.process_model = ProcessModel.load(proc_p)
                logger.info("Process model successfully loaded from %s", proc_p)
            except Exception as err:
                logger.error("Failed to load Process model from %s: %s", proc_p, err)
        else:
            logger.warning("Process model directory not found at %s", proc_p)

        # 2. Memory Model (CatBoost)
        mem_p = self.root_dir / "models" / "artifacts" / "memory"
        if mem_p.exists():
            try:
                self.memory_model = MemoryModel.load(mem_p)
                logger.info("Memory model successfully loaded from %s", mem_p)
            except Exception as err:
                logger.error("Failed to load Memory model from %s: %s", mem_p, err)
        else:
            logger.warning("Memory model directory not found at %s", mem_p)

        # 3. Command Model (DistilBERT)
        cmd_p = self.root_dir / "models" / "artifacts" / "command"
        if cmd_p.exists():
            try:
                self.command_model = CommandModel.load(cmd_p)
                logger.info("Command model successfully loaded from %s", cmd_p)
            except Exception as err:
                logger.error("Failed to load Command model from %s: %s", cmd_p, err)
        else:
            logger.warning("Command model directory not found at %s", cmd_p)

        # 4. Network Model (LightGBM)
        net_p = self.root_dir / "models" / "artifacts" / "network"
        if net_p.exists():
            try:
                self.network_model = NetworkModel.load(net_p)
                logger.info("Network model successfully loaded from %s", net_p)
            except Exception as err:
                logger.error("Failed to load Network model from %s: %s", net_p, err)
        else:
            logger.warning("Network model directory not found at %s", net_p)

        # 5. Multiclass Model (XGBoost) — trained on authentic custom dataset
        multi_p = self.root_dir / "models" / "multiclass" / "artifacts" / "multiclass_model.ubj"
        if not multi_p.exists():
            multi_p = self.root_dir / "models" / "multiclass" / "artifacts" / "multiclass_model.xgb"

        if multi_p.exists():
            try:
                self.multiclass_model = XGBClassifier()
                self.multiclass_model.load_model(str(multi_p))
                logger.info("Multiclass model loaded from %s", multi_p)
                # Load label_mapping.json (encoded int -> family slug)
                lm_path = multi_p.parent / "label_mapping.json"
                if lm_path.exists():
                    import json

                    with open(lm_path, encoding="utf-8") as _f:
                        raw_lm = json.load(_f)
                    self.multiclass_label_map = {
                        int(k): FAMILY_DISPLAY_NAMES.get(v, v.replace("_", " ").title())
                        for k, v in raw_lm.items()
                    }
                    logger.info(
                        "Multiclass label mapping loaded: %d classes",
                        len(self.multiclass_label_map),
                    )
            except Exception as err:
                logger.error("Failed to load Multiclass model from %s: %s", multi_p, err)
        else:
            logger.warning("Multiclass model file not found at %s", multi_p)

    def score_process(self, proc: ProcessFeatures | dict[str, Any] | pd.DataFrame) -> float:
        """Score process features using Process Model."""
        if not self.process_model:
            return 0.05
        if isinstance(proc, ProcessFeatures):
            df_row = pd.DataFrame([proc.model_dump()])
        elif isinstance(proc, dict):
            df_row = pd.DataFrame([proc])
        else:
            df_row = proc
        prob = self.process_model.predict_proba(df_row)[0]
        return float(prob)

    def score_command(self, cmd: CommandFeatures | str | dict[str, Any]) -> float:
        """Score command line using Command Model."""
        if not self.command_model:
            return 0.05
        if isinstance(cmd, CommandFeatures):
            cmd_text = cmd.raw_command_text
        elif isinstance(cmd, dict):
            cmd_text = str(cmd.get("raw_command_text", ""))
        else:
            cmd_text = str(cmd)
        prob = self.command_model.predict_proba([cmd_text])[0]
        return float(prob)

    def score_network(self, net: NetworkFeatures | dict[str, Any] | pd.DataFrame) -> float:
        """Score network activity using Network Model."""
        if not self.network_model:
            return 0.05
        if isinstance(net, NetworkFeatures):
            df_row = pd.DataFrame([net.model_dump()])
        elif isinstance(net, dict):
            df_row = pd.DataFrame([net])
        else:
            df_row = net
        prob = self.network_model.predict_proba(df_row)[0]
        return float(prob)

    def score_memory(self, mem: MemoryFeatures | dict[str, Any] | pd.DataFrame) -> float:
        """Score volatile memory structures using Memory Model."""
        if not self.memory_model:
            return 0.05
        if isinstance(mem, MemoryFeatures):
            df_row = pd.DataFrame([mem.model_dump()])
        elif isinstance(mem, dict):
            df_row = pd.DataFrame([mem])
        else:
            df_row = mem
        prob = self.memory_model.predict_proba(df_row)[0]
        return float(prob)

    def attribute_family(
        self,
        proc: ProcessFeatures,
        cmd: CommandFeatures,
        net: NetworkFeatures,
        mem: MemoryFeatures | None = None,
    ) -> tuple[str, float, dict[str, float]]:
        """Objective 3: Classify malware family using fused 4-modality vector."""
        if not self.multiclass_model:
            return "Unknown", 0.0, {}

        mem_features = mem or MemoryFeatures(
            sample_id=proc.sample_id,
            rwx_page_count=0,
            injected_code_regions=0,
            unmapped_executable_pages=0,
            vad_protection_anomaly_count=0,
            ldrmodules_inconsistencies=0,
            yara_shellcode_matches=0,
            mean_memory_entropy=0.0,
            max_memory_entropy=0.0,
        )

        fused_dict = {
            **proc.model_dump(include=set(PROCESS_FEATURE_COLS)),
            **cmd.model_dump(include=set(COMMAND_FEATURE_COLS)),
            **net.model_dump(include=set(NETWORK_FEATURE_COLS)),
            **mem_features.model_dump(include=set(MEMORY_FEATURE_COLS)),
        }

        try:
            cols = None
            if hasattr(self.multiclass_model, "get_booster"):
                try:
                    cols = self.multiclass_model.get_booster().feature_names
                except Exception:
                    cols = None
            if cols is None:
                cols = getattr(self.multiclass_model, "feature_names_in_", None)
            if cols is None:
                cols = ALL_NUMERIC_FEATURE_COLS

            fused_df = pd.DataFrame([fused_dict])[list(cols)].fillna(0.0).astype(float)

            probs = self.multiclass_model.predict_proba(fused_df)[0]
            argmax_idx = int(np.argmax(probs))
            # Use loaded label mapping (encoded index -> family name)
            raw_family = self.multiclass_label_map.get(argmax_idx, f"Family_{argmax_idx}")
            family_name = FAMILY_DISPLAY_NAMES.get(raw_family, raw_family)
            family_conf = float(probs[argmax_idx])

            prob_dist = {
                FAMILY_DISPLAY_NAMES.get(
                    self.multiclass_label_map.get(i, f"Family_{i}"),
                    self.multiclass_label_map.get(i, f"Family_{i}"),
                ): round(float(p), 4)
                for i, p in enumerate(probs)
            }

            return family_name, family_conf, prob_dist
        except Exception as err:
            logger.warning("Family attribution failed: %s", err)
            return "Unknown", 0.0, {}

    def detect(
        self,
        proc: ProcessFeatures,
        cmd: CommandFeatures,
        net: NetworkFeatures,
        mem: MemoryFeatures | None = None,
        force_memory_trigger: bool = False,
    ) -> dict[str, Any]:
        """Execute full hybrid detection pipeline (Objectives 2 and 3)."""
        proc_conf = self.score_process(proc)
        cmd_conf = self.score_command(cmd)
        net_conf = self.score_network(net)

        is_susp = (
            self.fusion_engine.is_suspicious(proc_conf, cmd_conf, net_conf) or force_memory_trigger
        )

        if is_susp:
            if mem is None:
                if self.mem_trigger is not None:
                    mem = self.mem_trigger.inspect_process(is_suspicious_context=True)
                else:
                    mem = MemoryFeatures(
                        sample_id=proc.sample_id,
                        rwx_page_count=1,
                        injected_code_regions=1,
                        unmapped_executable_pages=1,
                        vad_protection_anomaly_count=1,
                        ldrmodules_inconsistencies=1,
                    )
            mem_conf = self.score_memory(mem)
        else:
            if mem is None and self.mem_trigger is not None:
                mem = self.mem_trigger.inspect_process(is_suspicious_context=False)
            mem_conf = 0.05

        # Hybrid confidence fusion
        fusion_res: FusionResult = self.fusion_engine.evaluate(
            process_conf=proc_conf,
            command_conf=cmd_conf,
            network_conf=net_conf,
            memory_conf=mem_conf,
            force_memory_trigger=force_memory_trigger,
        )

        # Objective 3: Multi-class extension ONLY IF Malware
        family = None
        family_conf = None
        family_probs = None
        if fusion_res.is_malware:
            family, family_conf, family_probs = self.attribute_family(proc, cmd, net, mem)

        verdict_str = fusion_res.verdict.lower()
        classification_str = "MALICIOUS" if fusion_res.is_malware else "BENIGN"

        return {
            "verdict": verdict_str,
            "classification": classification_str,
            "confidence": fusion_res.confidence,
            "final_risk_score": round(fusion_res.confidence * 100, 2),
            "stage1_confidence": fusion_res.stage1_confidence,
            "is_malware": fusion_res.is_malware,
            "memory_triggered": fusion_res.memory_triggered,
            "fusion_threshold": fusion_res.threshold,
            "per_model": fusion_res.per_model,
            "modality_scores": fusion_res.per_model,
            "family": family,
            "family_confidence": round(family_conf, 4) if family_conf is not None else None,
            "family_probabilities": family_probs,
            "sample_features": {
                "process": proc.model_dump(),
                "command": cmd.model_dump(),
                "network": net.model_dump(),
                "memory": mem.model_dump() if mem else None,
            },
        }

    def detect_live_system(self, command_override: str | None = None) -> dict[str, Any]:
        """Poll host system live and run full detection."""
        if not (self.proc_collector and self.cmd_collector and self.net_collector):
            raise RuntimeError("Live collectors are unavailable because 'psutil' is not installed.")
        proc = self.proc_collector.collect()
        cmd = self.cmd_collector.collect(command_override=command_override)
        net = self.net_collector.collect()
        return self.detect(proc, cmd, net)

